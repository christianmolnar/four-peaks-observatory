#!/usr/bin/env node
// Prints the starting exposure parameters of the planner's exposure engine for the owner's rigs, as Markdown.
//
//   node scripts/planner-exposure-table.mjs [--out docs/guides/planner-exposure-table.md]
//
// The planner is TypeScript, so the script first compiles the modules it needs with the repo's own `tsc` into
// ~/.cache/fourpeaks-exposure-table (nothing else is written to the repo), then calls the real `exposureFor`.
// Without --out it prints to stdout; with --out it writes that file (the table in docs/guides/planner-exposure.md
// is this output).
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(homedir(), '.cache', 'fourpeaks-exposure-table');
const args = process.argv.slice(2);
const outPath = args.includes('--out') ? args[args.indexOf('--out') + 1] : null;

mkdirSync(OUT, { recursive: true });
writeFileSync(
  join(OUT, 'tsconfig.json'),
  JSON.stringify({
    compilerOptions: {
      target: 'ES2022', module: 'commonjs', moduleResolution: 'node10', esModuleInterop: true, resolveJsonModule: true,
      skipLibCheck: true, strict: true, outDir: join(OUT, 'js'), rootDir: join(ROOT, 'src'), typeRoots: [join(ROOT, 'node_modules', '@types')], types: [],
    },
    files: ['exposure/index.ts', 'optics/index.ts', 'profile/index.ts'].map((f) => join(ROOT, 'src', 'planner', f)),
  }),
);
execFileSync(join(ROOT, 'node_modules', '.bin', 'tsc'), ['-p', join(OUT, 'tsconfig.json')], { stdio: 'inherit' });

const require = createRequire(import.meta.url);
process.env.NODE_PATH = join(ROOT, 'node_modules');
require('node:module').Module._initPaths();
const planner = (m) => require(join(OUT, 'js', 'planner', m));
const { exposureFor, PRESETS, MODE_ORDER, SKY_LIMIT_K } = planner('exposure/index');
const { opticalTrain } = planner('optics/index');
const { resolveTrain, validateProfile } = planner('profile/index');

const profile = validateProfile(JSON.parse(readFileSync(join(ROOT, 'src/planner/data/sample-profile.json'), 'utf8')));
const camera = profile.equipment.cameras.find((c) => c.id === 'asi2600mc-duo');
const TRAINS = [
  ['C11 f/10', 'deep-c11-2600'],
  ['C11 + 0.7x reducer', 'deep-c11-reducer-2600'],
  ['C11 + HyperStar', 'wide-c11-hyperstar-2600'],
].map(([label, id]) => {
  const r = resolveTrain(profile, profile.trains.find((t) => t.id === id));
  const o = opticalTrain(r.scope, r.camera, r.accessory);
  return { label, train: { focalRatio: o.focalRatio, imageScale: o.imageScale }, fRatio: o.focalRatio };
});
const dual = profile.equipment.filters.find((f) => f.id === 'zwo-duo-band');
const FILTERS = [
  ['Broadband (no filter, 300 nm)', null, 'galaxy'],
  [`Dual-band (${dual.name}, ${dual.passbandWidthNm} nm)`, dual, 'nebula'],
];
const BORTLES = [4, 6, 8];
const night = { moonIllumination: 0, moonSeparationDeg: 90, moonUp: false, usableMinutes: 1000, acquisitionStart: null, transitTime: null };
const calc = (target, train, filter, bortle, preset) => {
  const r = exposureFor(target, { train, camera, filter }, { bortle }, night, { preset });
  if (!r.ok) throw new Error(`not ok: ${r.missing}`);
  return r;
};
const subText = (r) => {
  const tag = { 'read-noise': '', 'risk-cap': ' cap', saturation: ' sat', floor: ' floor', user: '' }[r.limitedBy.sub];
  return `${r.subSeconds}${tag}`;
};
const L = [];
L.push('<!-- Generated by scripts/planner-exposure-table.mjs from the exposure engine. Do not edit by hand. -->');
L.push('');
L.push(`Camera: ${camera.name} (${camera.pixelSizeUm} um pixels, read noise class ${camera.readNoiseClass}). No Moon, a clear night with room for the whole plan.`);
L.push('');
L.push('### Sub length in seconds, Quick / Balanced / Deep');
L.push('');
L.push('`cap` means the risk cap held it (read noise would ask for more), `sat` star saturation, `floor` the 15 s overhead floor. No mark means the sky-limited rule sets it.');
L.push('');
L.push('| Rig | Filter | Bortle 4 | Bortle 6 | Bortle 8 |');
L.push('|---|---|---|---|---|');
for (const t of TRAINS) {
  for (const [fl, filter, type] of FILTERS) {
    const cells = BORTLES.map((b) => MODE_ORDER.map((m) => subText(calc({ id: 'x', name: 'x', type }, t.train, filter, b, m))).join(' / '));
    L.push(`| ${t.label} (f/${Number(t.fRatio.toFixed(1))}) | ${fl} | ${cells.join(' | ')} |`);
  }
}
L.push('');
L.push(`### Sky-limited length before the clamps, Balanced (K = ${SKY_LIMIT_K}), seconds, and the extra noise at the sub it gets`);
L.push('');
L.push('| Rig | Filter | Bortle 4 | Bortle 6 | Bortle 8 |');
L.push('|---|---|---|---|---|');
for (const t of TRAINS) {
  for (const [fl, filter, type] of FILTERS) {
    const cells = BORTLES.map((b) => {
      const r = calc({ id: 'x', name: 'x', type }, t.train, filter, b, 'balanced');
      return `${Math.round(r.swampSeconds)} s, +${(r.readNoisePenalty * 100).toFixed(1)}% at ${r.subSeconds} s`;
    });
    L.push(`| ${t.label} | ${fl} | ${cells.join(' | ')} |`);
  }
}
L.push('');
L.push('### Total light in minutes, Quick / Balanced / Deep, by the object\'s surface brightness (the same on every rig: the same aperture)');
L.push('');
L.push('No mark: the preset\'s signal-to-noise target sets it. `k`: the diminishing-returns point sets it (the target is out of reach). `*`: the 30 minute minimum.');
L.push('');
L.push('| Object (mag per square arcsec) | Filter | Bortle 4 | Bortle 6 | Bortle 8 |');
L.push('|---|---|---|---|---|');
const rig = TRAINS[0];
for (const [name, mu] of [['Bright, 20', 20], ['Medium, 22', 22], ['Faint, 24', 24]]) {
  for (const [fl, filter, type] of FILTERS) {
    const cells = BORTLES.map((b) =>
      MODE_ORDER.map((m) => {
        const r = calc({ id: 'x', name: 'x', type, surfaceBrightnessMu: mu }, rig.train, filter, b, m);
        const tag = { 'snr-target': '', 'diminishing-returns': 'k', 'minimum-total': '*' }[r.limitedBy.total];
        return `${Math.round(r.integrationMin)}${tag}`;
      }).join(' / '),
    );
    L.push(`| ${name} (${type === 'galaxy' ? 'continuum' : 'emission'}) | ${fl} | ${cells.join(' | ')} |`);
  }
}
L.push('');
L.push('### Presets');
L.push('');
L.push('| Preset | K | SNR target | Stops when 30 more minutes add under | Longest sub | Dither |');
L.push('|---|---|---|---|---|---|');
for (const m of MODE_ORDER) {
  const p = PRESETS[m];
  L.push(`| ${p.label} | ${p.swampK} | ${p.snrTarget} | ${p.maxNextHalfHourGain * 100}% | ${p.riskCapS} s | every ${p.dither.everyFrames} subs, not more often than every ${p.dither.minIntervalS} s |`);
}
const text = L.join('\n') + '\n';
if (outPath) writeFileSync(resolve(outPath), text);
else process.stdout.write(text);

#!/usr/bin/env node
// Derives src/planner/plan/brightness-percentiles.ts from the bundled OpenNGC extract.
//
//   node scripts/build-brightness-percentiles.mjs [--check]
//
// For each scoring class, ONE measure is read for every object that has it, sorted brightest first (a smaller number
// is brighter for both), and 101 cut points are kept: cut[k] is the value at the k-th percentile of that order.
// `--check` compares instead of writing (exit 1 when the file is stale). Re-run when the extract changes; a jest test
// also re-derives the tables from the asset.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ASSET = 'openngc-v20260501-r3.json';
const OUT = join(ROOT, 'src', 'planner', 'plan', 'brightness-percentiles.ts');

// Keep in step with `brightnessClass` in src/planner/plan/brightness.ts (a test re-derives the tables with that function).
const GALAXY = ['galaxy', 'galaxy-group'];
const CLUSTER = ['open-cluster', 'globular-cluster', 'asterism'];
const NEBULA = ['nebula', 'supernova-remnant', 'planetary-nebula'];
// galaxySB: measured surface brightness (a computed one, for the few galaxies with none, is ranked against these, not part of them);
// galaxyMag: integrated V magnitude; galaxy: the blend of the two (see below), the class's own scale;
// cluster, nebula (nebula, SNR, planetary): integrated V magnitude; other: V magnitude of every object that has one.
const MEASURES = {
  galaxySB: (o) => (GALAXY.includes(o.type) && o.surfaceBrightness !== undefined && o.sbComputed !== true ? o.surfaceBrightness : undefined),
  galaxyMag: (o) => (GALAXY.includes(o.type) ? o.mag : undefined),
  cluster: (o) => (CLUSTER.includes(o.type) ? o.mag : undefined),
  nebula: (o) => (NEBULA.includes(o.type) ? o.mag : undefined),
  other: (o) => o.mag,
};

export function cutPoints(values) {
  const s = [...values].sort((a, b) => a - b);
  return Array.from({ length: 101 }, (_, k) => s[Math.round((k * (s.length - 1)) / 100)]);
}

// Keep in step with `fractionBrighter` in brightness.ts.
export function fractionBrighter(value, cuts) {
  const last = cuts.length - 1;
  let lo = 0;
  while (lo <= last && cuts[lo] < value) lo++;
  if (lo === 0) return 0;
  if (lo > last) return 1;
  if (cuts[lo] === value) {
    let hi = lo;
    while (hi < last && cuts[hi + 1] === value) hi++;
    return (lo + hi) / (2 * last);
  }
  return (lo - 1 + (value - cuts[lo - 1]) / (cuts[lo] - cuts[lo - 1])) / last;
}

const raw = JSON.parse(readFileSync(join(ROOT, 'public', 'catalog', ASSET), 'utf8'));
const tables = Object.fromEntries(
  Object.entries(MEASURES).map(([name, measure]) => {
    const values = raw.objects.map(measure).filter((v) => v !== undefined);
    return [name, { n: values.length, cuts: cutPoints(values) }];
  }),
);

// A galaxy is scored on where it stands in surface brightness and in total light, weighted by its size: a small one on
// its surface brightness, a large one on its magnitude (see `galaxyBlend` in brightness.ts; keep in step). The blend is
// not uniform, so the class's own table is the percentile cut points of the blend over every galaxy, and a galaxy is
// then scored by where its blend stands in that: the top tenth is +10.
const MAG_WEIGHT_FROM_ARCMIN = 2;
const MAG_WEIGHT_FULL_ARCMIN = 10;
export function magnitudeWeight(majorArcmin) {
  if (majorArcmin === undefined) return 0.5;
  const t = Math.log(majorArcmin / MAG_WEIGHT_FROM_ARCMIN) / Math.log(MAG_WEIGHT_FULL_ARCMIN / MAG_WEIGHT_FROM_ARCMIN);
  return Math.max(0, Math.min(1, t));
}
const blends = raw.objects
  .filter((o) => GALAXY.includes(o.type))
  .map((o) => {
    const sb = o.surfaceBrightness === undefined ? undefined : fractionBrighter(o.surfaceBrightness, tables.galaxySB.cuts);
    const mag = o.mag === undefined ? undefined : fractionBrighter(o.mag, tables.galaxyMag.cuts);
    if (sb === undefined || mag === undefined) return sb ?? mag;
    const w = magnitudeWeight(o.majorArcmin);
    return (1 - w) * sb + w * mag;
  })
  .filter((v) => v !== undefined);
tables.galaxy = { n: blends.length, cuts: cutPoints(blends) };

const rows = Object.entries(tables).map(
  ([name, t]) => `  ${name}: { n: ${t.n}, cuts: [${t.cuts.join(', ')}] },`,
);
const text = `// GENERATED by scripts/build-brightness-percentiles.mjs from public/catalog/${ASSET}; do not edit.
// Percentile cut points of each class's brightness measure (galaxy: the blend of galaxySB and galaxyMag, see the script), brightest first: cuts[k] is the value at the k-th percentile
// (k = 0..100) of the class sorted ascending. A smaller value is brighter. \`n\` is how many objects went in.
export interface PercentileTable {
  n: number;
  cuts: readonly number[];
}

export const BRIGHTNESS_PERCENTILES = {
${rows.join('\n')}
} as const satisfies Record<string, PercentileTable>;
`;

if (process.argv.includes('--check')) {
  const have = readFileSync(OUT, 'utf8');
  if (have !== text) {
    console.error(`${OUT} is stale: run node scripts/build-brightness-percentiles.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
